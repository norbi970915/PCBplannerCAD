//! Fabrication package: every Gerber layer, PTH/NPTH drills, optional
//! pick-and-place and BOM, a README layer map, and optionally a zip of it all.
//!
//! File names (`<p>` = sanitized project name, "board" when empty):
//! `<p>.GTL`, `<p>.G1`…, `<p>.GBL`, `<p>.GTS`, `<p>.GBS`, `<p>.GTP`, `<p>.GBP`,
//! `<p>.GTO`, `<p>.GBO`, `<p>.GKO`, `<p>-PTH.drl`, `<p>-NPTH.drl`,
//! `<p>_pnp.csv`, `<p>_bom.csv`, `README.txt`, and `<p>_fab.zip`.

use std::fmt::Write as _;
use std::io::Write as _;
use std::path::{Path, PathBuf};

use pcbplannercad_core::document::Document;
use pcbplannercad_core::pcb::BoardSettings;
use pcbplannercad_core::pcb::geometry::board_settings;
use pcbplannercad_core::units::to_mm;
use serde::{Deserialize, Serialize};

use crate::OutputError;
use crate::assembly::{BomFormat, PnpFormat, bom_csv, pick_and_place_csv};
use crate::excellon::write_drill;
use crate::gerber::{GerberOptions, VERSION, creation_date, file_function, layer_file_name, sanitize_file_stem, standard_layers, write_layer};

#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct FabOptions {
    pub gerber: GerberOptions,
    pub pnp: Option<PnpFormat>,
    pub bom: Option<BomFormat>,
    pub zip: bool,
}

/// Publishes a complete package into a new folder. Existing destinations are
/// rejected; files and optional ZIP are prepared before the folder is published.
pub fn write_package(doc: &Document, out_dir: &Path, opts: &FabOptions) -> Result<Vec<PathBuf>, OutputError> {
    if std::fs::symlink_metadata(out_dir).is_ok() { return Err(OutputError::Invalid("Choose a new package folder; the destination already exists".into())); }
    let default = BoardSettings::default();
    let board = board_settings(doc).map_or(&default, |(_, b)| b);
    let project = &opts.gerber.project_name;
    let stem = sanitize_file_stem(project);
    // (file name, contents, description)
    let mut files: Vec<(String, String, String)> = Vec::new();
    for (f, ext) in standard_layers(doc) {
        let (function, _) = file_function(board, f)?;
        files.push((layer_file_name(project, &ext), write_layer(doc, f, &opts.gerber)?, format!("{} (Gerber X2, {function})", f.label(board))));
    }
    files.push((format!("{stem}-PTH.drl"), write_drill(doc, true)?, "Plated holes: vias and through-hole pads (Excellon 2, metric)".into()));
    files.push((format!("{stem}-NPTH.drl"), write_drill(doc, false)?, "Non-plated holes (Excellon 2, metric)".into()));
    if let Some(fmt) = opts.pnp {
        files.push((format!("{stem}_pnp.csv"), pick_and_place_csv(doc, fmt, None), format!("Pick and place, both sides ({fmt:?} format)")));
    }
    if let Some(fmt) = opts.bom {
        files.push((format!("{stem}_bom.csv"), bom_csv(doc, fmt), format!("Bill of materials ({fmt:?} format)")));
    }
    let readme = readme(project, board, &files);
    files.push(("README.txt".into(), readme, String::new()));

    let mut bundle: Vec<(PathBuf,Vec<u8>)> = Vec::with_capacity(files.len()+1);
    if opts.zip {
        let zip_err = |e: zip::result::ZipError| OutputError::Invalid(format!("zip: {e}"));
        let mut z = zip::ZipWriter::new(std::io::Cursor::new(Vec::new()));
        let o = zip::write::SimpleFileOptions::default().compression_method(zip::CompressionMethod::Deflated);
        for (name,content,_) in &files {z.start_file(name.as_str(),o).map_err(zip_err)?;z.write_all(content.as_bytes())?;}
        bundle.push((PathBuf::from(format!("{stem}_fab.zip")),z.finish().map_err(zip_err)?.into_inner()));
    }
    let zip=bundle.pop();
    bundle.extend(files.into_iter().map(|(name,content,_)|(PathBuf::from(name),content.into_bytes())));
    if let Some(zip)=zip {bundle.push(zip);}
    let written=bundle.iter().map(|(path,_)|out_dir.join(path)).collect();
    pcbplannercad_core::storage::create_bundle(out_dir,&bundle)?;
    Ok(written)
}

fn readme(project: &str, board: &BoardSettings, files: &[(String, String, String)]) -> String {
    let name = if project.trim().is_empty() { "(unnamed)" } else { project.trim() };
    let mut s = String::new();
    let _ = writeln!(s, "Fabrication data for {name}");
    let _ = writeln!(s, "Generated by pCAD {VERSION} on {}", creation_date());
    s.push('\n');
    let cu = board.stackup.copper_layers().len();
    let _ = writeln!(s, "Board: {cu} copper layers, {:.3} mm nominal thickness", to_mm(board.stackup.thickness()));
    s.push_str("Units: millimeters. Gerber: RS-274X with X2 attributes, all layers viewed from the top (bottom layers not mirrored).\n");
    s.push_str("Solder mask files are negative (the image shows mask openings). Drill files: Excellon 2, metric, absolute, slots as G85.\n");
    s.push('\n');
    s.push_str("Files:\n");
    let w = files.iter().map(|f| f.0.len()).max().unwrap_or(0);
    for (file, _, desc) in files.iter().filter(|f| !f.2.is_empty()) {
        let _ = writeln!(s, "  {file:<w$}  {desc}");
    }
    s.replace('\n', "\r\n")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::gerber::test_board::{board_doc, footprint_with, place, smd_pad};
    use pcbplannercad_core::item::PadShape;
    use pcbplannercad_core::units::{Point, mm};
    use std::io::Read as _;

    fn temp_dir(tag: &str) -> PathBuf {
        let nanos = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap().as_nanos();
        std::env::temp_dir().join(format!("pcbplannercad-fab-{tag}-{}-{nanos}", std::process::id()))
    }

    #[test]
    fn package_writes_expected_files_and_zip() {
        let f = footprint_with(vec![smd_pad("1", -0.8, 1.0, 0.5, PadShape::Rect, 0.0), smd_pad("2", 0.8, 1.0, 0.5, PadShape::Rect, 0.0)]);
        let doc = board_doc(vec![place("R1", "L/R", Point::new(mm(10.0), mm(10.0)), 0.0)], &[("L/R", f)]);
        let dir = temp_dir("pkg");
        let opts = FabOptions {
            gerber: GerberOptions { project_name: "My:Board".into(), ..Default::default() },
            pnp: Some(PnpFormat::Jlc),
            bom: Some(BomFormat::Jlc),
            zip: true,
        };
        let written = write_package(&doc, &dir, &opts).unwrap();
        let names: Vec<String> = written.iter().map(|p| p.file_name().unwrap().to_string_lossy().into_owned()).collect();
        let expected = [
            "My_Board.GTL",
            "My_Board.GBL",
            "My_Board.GTS",
            "My_Board.GBS",
            "My_Board.GTP",
            "My_Board.GBP",
            "My_Board.GTO",
            "My_Board.GBO",
            "My_Board.GKO",
            "My_Board-PTH.drl",
            "My_Board-NPTH.drl",
            "My_Board_pnp.csv",
            "My_Board_bom.csv",
            "README.txt",
            "My_Board_fab.zip",
        ];
        assert_eq!(names, expected);
        for p in &written {
            assert!(p.is_file(), "{p:?}");
        }
        let gtl = std::fs::read_to_string(dir.join("My_Board.GTL")).unwrap();
        assert!(gtl.contains("%TF.FileFunction,Copper,L1,Top*%") && gtl.ends_with("M02*\n"));
        let readme = std::fs::read_to_string(dir.join("README.txt")).unwrap();
        assert!(readme.contains("My_Board.GTS") && readme.contains("Top Solder Mask"));

        let mut z = zip::ZipArchive::new(std::fs::File::open(dir.join("My_Board_fab.zip")).unwrap()).unwrap();
        let mut in_zip: Vec<String> = z.file_names().map(|n| n.unwrap().into_owned()).collect();
        in_zip.sort();
        let mut want: Vec<String> = expected[..expected.len() - 1].iter().map(|s| s.to_string()).collect();
        want.sort();
        assert_eq!(in_zip, want);
        let mut content = String::new();
        z.by_name("My_Board.GTL").unwrap().read_to_string(&mut content).unwrap();
        assert_eq!(content, gtl);
        std::fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn existing_package_is_preserved_when_a_later_output_is_blocked() {
        let doc=board_doc(vec![],&[]);let dir=temp_dir("existing");std::fs::create_dir(&dir).unwrap();
        std::fs::write(dir.join("board.GTL"),b"previous copper").unwrap();std::fs::create_dir(dir.join("README.txt")).unwrap();
        assert!(write_package(&doc,&dir,&FabOptions::default()).is_err());
        assert_eq!(std::fs::read(dir.join("board.GTL")).unwrap(),b"previous copper");
        assert_eq!(std::fs::read_dir(&dir).unwrap().count(),2);
        std::fs::remove_dir_all(dir).unwrap();
    }

    #[test]
    fn existing_empty_folder_is_rejected_without_writes() {
        let doc=board_doc(vec![],&[]);let dir=temp_dir("empty");std::fs::create_dir(&dir).unwrap();
        assert!(write_package(&doc,&dir,&FabOptions::default()).is_err());assert_eq!(std::fs::read_dir(&dir).unwrap().count(),0);
        std::fs::remove_dir_all(dir).unwrap();
    }

    #[test]
    fn package_without_extras_or_zip() {
        let doc = board_doc(vec![], &[]);
        let dir = temp_dir("min");
        let written = write_package(&doc, &dir, &FabOptions::default()).unwrap();
        let names: Vec<String> = written.iter().map(|p| p.file_name().unwrap().to_string_lossy().into_owned()).collect();
        assert_eq!(names.len(), 9 + 2 + 1);
        assert!(names.contains(&"board.GKO".to_string()));
        assert!(!names.iter().any(|n| n.ends_with(".zip") || n.ends_with(".csv")));
        std::fs::remove_dir_all(&dir).unwrap();
    }
}
